import { OpenAI } from 'openai';
import { z } from 'zod';
import type { SiteMap } from './discoveryAgent.js';
import type { LogCallback } from './browserAgent.js';
import { JOURNEY_PLANNER_SYSTEM_PROMPT } from './prompts.js';
import crypto from 'node:crypto';

// ---------------------------------------------------------------------------
// TypeScript Interfaces & Zod Validation Schemas
// ---------------------------------------------------------------------------

export const TestStepActionSchema = z.enum([
  'NAVIGATE',
  'CLICK',
  'FILL',
  'SELECT',
  'ASSERT_TEXT',
  'ASSERT_VISIBLE',
]);

export const TestStepSchema = z.object({
  stepNumber: z.number(),
  description: z.string(),
  action: TestStepActionSchema,
  targetUrl: z.string().optional(),
  selector: z.string().optional(),
  value: z.string().optional(),
  expectedOutcome: z.string().optional(),
});

export const TestJourneySchema = z.object({
  id: z.string(),
  title: z.string(),
  description: z.string(),
  priority: z.enum(['HIGH', 'MEDIUM', 'LOW']),
  steps: z.array(TestStepSchema),
});

export const TestPlanSchema = z.object({
  id: z.string(),
  targetBaseUrl: z.string(),
  generatedAt: z.string(),
  summary: z.string(),
  journeys: z.array(TestJourneySchema),
});

export type TestStepAction = z.infer<typeof TestStepActionSchema>;
export type TestStep = z.infer<typeof TestStepSchema>;
export type TestJourney = z.infer<typeof TestJourneySchema>;
export type TestPlan = z.infer<typeof TestPlanSchema>;

export interface PlannerOptions {
  userIntent?: string;
  model?: string;
}

/**
 * ---------------------------------------------------------------------------
 * Journey Planner Agent (Day 4)
 * ---------------------------------------------------------------------------
 * Consumes the SiteMap JSON generated by the Discovery Agent and produces
 * a structured, executable TestPlan with multi-step journeys.
 *
 * If OPENAI_API_KEY is available:
 *   Uses OpenAI GPT with structured JSON mode.
 * If OPENAI_API_KEY is missing or invalid:
 *   Gracefully falls back to a deterministic rule-based planner that constructs
 *   end-to-end shopping and form-filling test journeys from the discovered DOM.
 */
export async function runJourneyPlanner(
  siteMap: SiteMap,
  log?: LogCallback,
  options: PlannerOptions = {}
): Promise<TestPlan> {
  const emitLog: LogCallback = async (step, msg, level = 'INFO', meta) => {
    if (log) {
      await log(step, msg, level, meta);
    } else {
      console.log(`[${step}] (${level}) ${msg}`);
    }
  };

  await emitLog('PLANNER_START', `Analyzing SiteMap with ${siteMap.totalPages} discovered routes...`, 'INFO', {
    baseUrl: siteMap.baseUrl,
    totalPages: siteMap.totalPages,
  });

  const apiKey = process.env.OPENAI_API_KEY;

  if (apiKey) {
    try {
      await emitLog('PLANNER_LLM', 'Generating test plan using OpenAI reasoning model...', 'INFO');
      const plan = await generatePlanWithOpenAI(siteMap, apiKey, options);
      await emitLog(
        'PLANNER_SUCCESS',
        `Generated ${plan.journeys.length} test journeys with ${plan.journeys.reduce((sum, j) => sum + j.steps.length, 0)} total steps.`,
        'SUCCESS'
      );
      return plan;
    } catch (err: any) {
      await emitLog(
        'PLANNER_FALLBACK',
        `OpenAI planner error (${err.message}). Using deterministic fallback planner.`,
        'WARN'
      );
    }
  } else {
    await emitLog(
      'PLANNER_OFFLINE',
      'No OPENAI_API_KEY detected. Using deterministic rule-based planner.',
      'INFO'
    );
  }

  // Deterministic Fallback Planner (100% offline & reliable)
  const plan = generateDeterministicPlan(siteMap, options.userIntent);
  await emitLog(
    'PLANNER_SUCCESS',
    `Constructed ${plan.journeys.length} test journeys using application topology.`,
    'SUCCESS'
  );
  return plan;
}

/**
 * Calls OpenAI Chat Completions API with structured JSON output
 */
async function generatePlanWithOpenAI(
  siteMap: SiteMap,
  apiKey: string,
  options: PlannerOptions
): Promise<TestPlan> {
  const client = new OpenAI({ apiKey });

  const prompt = `
Analyze the following SiteMap and produce an executable TestPlan for user verification.
User Intent / Objective: "${options.userIntent || 'Comprehensive exploratory user journey testing'}"

Base URL: ${siteMap.baseUrl}
Discovered Routes:
${JSON.stringify(siteMap.pages, null, 2)}

Return strict JSON with this exact schema:
{
  "id": "plan_${Date.now()}",
  "targetBaseUrl": "${siteMap.baseUrl}",
  "generatedAt": "${new Date().toISOString()}",
  "summary": "Brief summary of test coverage",
  "journeys": [
    {
      "id": "journey_1",
      "title": "Journey Title",
      "description": "What this test validates",
      "priority": "HIGH",
      "steps": [
        {
          "stepNumber": 1,
          "description": "Step description",
          "action": "NAVIGATE | CLICK | FILL | SELECT | ASSERT_TEXT | ASSERT_VISIBLE",
          "targetUrl": "string (for NAVIGATE)",
          "selector": "string (for CLICK, FILL, ASSERT)",
          "value": "string (for FILL, SELECT, or expected text)",
          "expectedOutcome": "string"
        }
      ]
    }
  ]
}
`.trim();

  const response = await client.chat.completions.create({
    model: options.model || 'gpt-4o-mini',
    messages: [
      { role: 'system', content: JOURNEY_PLANNER_SYSTEM_PROMPT },
      { role: 'user', content: prompt },
    ],
    response_format: { type: 'json_object' },
    temperature: 0.2,
  });

  const rawJson = response.choices[0]?.message?.content || '{}';
  const parsed = JSON.parse(rawJson);

  // Validate output conforms strictly to our schema
  return TestPlanSchema.parse(parsed);
}

/**
 * Deterministic Fallback Planner
 * Analyzes the SiteMap graph and constructs end-to-end shopping & form test journeys
 */
export function generateDeterministicPlan(
  siteMap: SiteMap,
  userIntent?: string
): TestPlan {
  const journeys: TestJourney[] = [];
  const pages = Object.values(siteMap.pages);

  // Find home / catalog page
  const homePage = pages[0] || {
    url: siteMap.baseUrl,
    title: 'Home',
    inputs: [],
    actions: [],
    links: [],
  };

  // Find a page with a form (e.g. checkout or contact form)
  const formPage = pages.find((p) => p.inputs.length > 0) || homePage;

  // Journey 1: Primary Happy-Path User Flow
  const steps: TestStep[] = [];
  let stepIdx = 1;

  // Step 1: Navigate to Base/Catalog
  steps.push({
    stepNumber: stepIdx++,
    description: `Navigate to application entry point: ${homePage.url}`,
    action: 'NAVIGATE',
    targetUrl: homePage.url,
    expectedOutcome: `Page loaded with title containing "${homePage.title || 'Store'}"`,
  });

  // Step 2: Trigger catalog action (e.g. Add to Cart button)
  const addAction = homePage.actions.find(
    (a) => a.id?.includes('add-to-cart') || a.text.toLowerCase().includes('add')
  ) || homePage.actions[0];

  if (addAction) {
    steps.push({
      stepNumber: stepIdx++,
      description: `Click primary action: "${addAction.text}"`,
      action: 'CLICK',
      selector: addAction.selector,
      expectedOutcome: 'Item added or state updated in interface',
    });
  }

  // Step 3: Navigate to intermediate page (e.g. cart or form page)
  if (formPage && formPage.url !== homePage.url) {
    steps.push({
      stepNumber: stepIdx++,
      description: `Navigate to form flow: ${formPage.url}`,
      action: 'NAVIGATE',
      targetUrl: formPage.url,
      expectedOutcome: `Form screen loaded with ${formPage.inputs.length} fields`,
    });
  }

  // Step 4+: Fill all discovered form inputs
  const sampleValues: Record<string, string> = {
    name: 'Alex Rivera',
    email: 'alex.rivera@example.com',
    card: '4242424242424242',
    date: '12/28',
    cvv: '123',
    city: 'San Francisco',
    zip: '94107',
    address: '100 Market St',
  };

  for (const input of formPage.inputs) {
    let mockVal = 'Sample Text';
    const lowerName = (input.name || input.id || input.label || '').toLowerCase();

    for (const [key, val] of Object.entries(sampleValues)) {
      if (lowerName.includes(key)) {
        mockVal = val;
        break;
      }
    }

    steps.push({
      stepNumber: stepIdx++,
      description: `Fill field [${input.label || input.name || input.selector}]`,
      action: 'FILL',
      selector: input.selector,
      value: mockVal,
      expectedOutcome: `Field populated with "${mockVal}"`,
    });
  }

  // Step Submit: Click submit button if present
  const submitAction = formPage.actions.find((a) => a.type === 'submit') || formPage.actions[0];
  if (submitAction) {
    steps.push({
      stepNumber: stepIdx++,
      description: `Submit form via "${submitAction.text}"`,
      action: 'CLICK',
      selector: submitAction.selector,
      expectedOutcome: 'Form submitted and transaction initiated',
    });
  }

  // Final Step: Assertion of outcome
  steps.push({
    stepNumber: stepIdx++,
    description: 'Verify successful order confirmation or outcome state',
    action: 'ASSERT_VISIBLE',
    selector: '#order-success-title',
    expectedOutcome: 'Success confirmation screen visible',
  });

  journeys.push({
    id: 'journey_happy_path',
    title: 'End-to-End Primary Transaction Journey',
    description: userIntent || 'Execute complete browse, populate, and submission flow.',
    priority: 'HIGH',
    steps,
  });

  return {
    id: `plan_${crypto.randomUUID().slice(0, 8)}`,
    targetBaseUrl: siteMap.baseUrl,
    generatedAt: new Date().toISOString(),
    summary: `Autonomous Test Plan covering ${pages.length} discovered routes with ${steps.length} sequential execution steps.`,
    journeys,
  };
}
